export function applyTheme(name: ThemeName): void {
  const t = themes[name];
  const root = document.documentElement;
  root.style.setProperty('--color-bg', t.bg);
  root.style.setProperty('--color-surface', t.surface);
  root.style.setProperty('--color-surface2', t.surface2);
  root.style.setProperty('--color-border', t.border);
  root.style.setProperty('--color-text', t.text);
  root.style.setProperty('--color-text-muted', t.textMuted);
  root.style.setProperty('--color-text-subtle', t.textSubtle);
  root.style.setProperty('--color-primary', t.primary);
  root.style.setProperty('--color-primary-hover', t.primaryHover);
  root.style.setProperty('--color-correct', t.correct);
  root.style.setProperty('--color-incorrect', t.incorrect);
  root.style.setProperty('--color-current', t.current);
  root.style.setProperty('--color-extra', t.extra);
  root.style.setProperty('--color-missed', t.missed);
  root.style.setProperty('--color-caret', t.caret);
  root.style.setProperty('--color-accent', t.accent);
}
